#!/usr/bin/env python3
"""Bundle data/experiments/* into docs/data/db.js for the website.
The site computes fold change, blank correction and size normalization itself,
so this file only carries metadata and raw fluorescence. Usage: python scripts/build_site.py"""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from rzlib import load_experiment, experiment_folders

here = os.path.dirname(os.path.abspath(__file__))
root = os.path.join(here, "..", "data", "experiments")
out = os.path.join(here, "..", "docs", "data", "db.js")
exps, samples = [], []
for f in experiment_folders(root):
    meta, ss, errors, _ = load_experiment(f)
    if errors:
        sys.exit(f"{f} has validation errors; run scripts/validate.py")
    exps.append(meta)
    for s in ss:
        r = {"e": meta["id"], "id": s["id"], "plate": s["plate"], "type": s["type"], "t": s["t"], "len": s["len"],
             "h": [int(h) if float(h).is_integer() else h for h in s["h"]],
             "f": [int(v) if float(v).is_integer() else round(v, 4) for v in s["f"]]}
        for k in ("g", "fam", "mort", "date", "excl", "notes"):
            if s[k]:
                r[k] = s[k]
        samples.append(r)
exps.sort(key=lambda m: (m["species"], m["date_start"], m["id"]))
os.makedirs(os.path.dirname(out), exist_ok=True)
with open(out, "w", encoding="utf-8") as fh:
    fh.write("/* Generated by scripts/build_site.py. Do not edit by hand. */\nwindow.RESAZURIN_DB = ")
    json.dump({"experiments": exps, "samples": samples}, fh, separators=(",", ":"))
    fh.write(";\n")
print(f"wrote {out}: {len(exps)} experiments, {len(samples)} wells, {os.path.getsize(out) / 1e6:.2f} MB")
